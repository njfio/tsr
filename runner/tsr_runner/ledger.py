"""Outputs (spec section 9): ledger/<domain>.md in the holds format, patches for tsr_formal.ROWS, report.md."""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .schema import Relation


def ledger_md(domain: str, run_id: str, rows: list[dict], collisions: list[dict], breaks: list[dict],
              decoy: dict | None, records: dict[str, Relation], mock: bool) -> str:
    L = []
    L.append(f"# {domain}: what the rule forced, what collided, what stays open")
    L.append("")
    L.append(f"Run `{run_id}`." + (" **MOCK RUN: no model was consulted; plumbing only.**" if mock else ""))
    L.append("")
    tears = [b for b in breaks if b["is_break"]]
    L.append("## Tears")
    L.append("")
    if tears:
        for b in tears:
            L.append(f"- **{' × '.join(b['rows'])}** (layer {b['layer']}). " + json.dumps(b["failing_check"], ensure_ascii=False)[:400])
            L.append(f"  Minimal change that dissolves it: {b['minimal_change_to_dissolve']}")
    else:
        L.append("None survived. " + ("(Nothing could: a mock run.)" if mock else ""))
    L.append("")
    L.append("## Candidate rows")
    L.append("")
    L.append("Forced rows with no collision. Each is a reflection the rule produced without a judgment call, that the generators agreed on, and that the opponent could not flip.")
    L.append("")
    collided = {rid for c in collisions for rid in c["rows"]}
    for r in rows:
        if not r["candidate_forced"] or r["record_id"] in collided:
            continue
        rec = records[r["record_id"]]
        c = r["consensus"]
        L.append(f"- ### {rec.title}")
        L.append(f"  Physical: {rec.statement}")
        L.append(f"  Shape: **{c['shape']}** (criteria {', '.join(c['rule_trace'])}). Formula: `{c['reflected_formula'] or '—'}`")
        L.append(f"  Reflected: {c['reflected_sentence']}")
        L.append(f"  Agreement: {r['agreement']['majority_n']}/{r['agreement']['n_total']}; opponent: {'flipped' if r['opponent_flipped'] else 'no rule-compliant alternative'}")
        L.append("")
    L.append("## Connections")
    L.append("")
    conns = [c for c in collisions if c.get("status") == "book_resolves"]
    if conns:
        for c in conns:
            L.append(f"- {' × '.join(c['rows'])}: reads as a collision; the book resolves it at {c.get('book_ref','?')}. A documentation gap, not a break.")
    else:
        L.append("None fell out of Layer C in this run. (Connections are never sought.)")
    L.append("")
    L.append("## Open")
    L.append("")
    for r in rows:
        if r["candidate_forced"]:
            continue
        rec = records[r["record_id"]]
        L.append(f"- **{rec.title}**: " + " / ".join(r["gate"]))
        if r["decision"]["alternates"]:
            for a in r["decision"]["alternates"]:
                L.append(f"  - alternate standard form ({a['form']}): {a['shape']} — {a['statement']}")
    L.append("")
    if decoy:
        L.append("## Decoy margin")
        L.append("")
        L.append(f"T mean {decoy['mean'].get('T')}, D {decoy['mean'].get('D')}, W {decoy['mean'].get('W')}; "
                 f"margins {decoy['margin_vs_D']} / {decoy['margin_vs_W']} against required {decoy['required_margins']}. "
                 f"{'Passed.' if decoy['passed'] else 'FAILED: rows marked curated and excluded from collision testing.'}")
        L.append("")
    return "\n".join(L)


def patch_rows(rows: list[dict], records: dict[str, Relation], run_id: str) -> str:
    """New ROWS entries for tests/tsr_formal.py, in its tuple format."""
    L = ["# Generated by tsr-ledger from run " + run_id + ". Append to tests/tsr_formal.py ROWS.",
         "# (name, ruling, has_mass, definition, costs, source)", "NEW_ROWS = ["]
    for r in rows:
        if not r["candidate_forced"]:
            continue
        rec = records[r["record_id"]]
        has_mass = any(v.quantity == "mass m" for v in rec.variables)
        definition = r["decision"]["features"]["is_identity"]
        costs = r["decision"]["features"]["cost_count"]
        ruling = "invert" if r["consensus"]["shape"] == "turns around" else "keep"
        L.append(f"    ({rec.title!r}, {ruling!r}, {has_mass}, {definition}, {costs}, {('run ' + run_id + ': ' + rec.id)!r}),")
    L.append("]")
    return "\n".join(L)


def report_md(run_id: str, domain: str, rows: list[dict], collisions: list[dict], breaks: list[dict],
              decoy: dict | None, calibration: dict, criteria: dict, lexicon: dict, canary: dict | None,
              roster_problems: list[str], mock: bool) -> str:
    n = len(rows)
    forced = [r for r in rows if r["candidate_forced"]]
    open_rows = [r for r in rows if not r["candidate_forced"]]
    why = Counter()
    for r in open_rows:
        for g in r["gate"]:
            why[g.split(":")[0]] += 1
    tears = [b for b in breaks if b["is_break"]]
    hyp = ("MOCK RUN: supports nothing." if mock else
           "a break survived; consistent with the flexible-joints hypothesis only if it is upstream of a joint closed in 5.3, "
           "otherwise it is a break in the structure" if tears else
           "no forced row collided; consistent with 'describes one thing' to the extent of the rows forced here, "
           "and only if the decoy margin passed")
    L = [f"# Run {run_id}: {domain}", "",
         f"- Criteria v{criteria.get('version')}, lexicon v{lexicon.get('version')} ({lexicon.get('criterion_id')}).",
         f"- Calibration: {calibration['matched']}/{calibration['total']} book rulings reproduced from records alone; pending author rulings: {calibration['pending_author']}.",
         f"- Rows run: {n}. Rows forced: {len(forced)}. Open: {len(open_rows)}.",
         "- Why rows stayed open: " + (", ".join(f"{k} ({c})" for k, c in why.most_common()) or "—"),
         f"- Collisions found: {len([c for c in collisions if c.get('status') != 'informational'])} (informational reading-parity notes: {len([c for c in collisions if c.get('status') == 'informational'])}).",
         f"- Breaks surviving Layer C: {len(tears)}.",
         f"- Decoy margin: " + (f"T {decoy['mean'].get('T')} / D {decoy['mean'].get('D')} / W {decoy['mean'].get('W')}, {'passed' if decoy['passed'] else 'FAILED (curated)'}" if decoy else "not run"),
         f"- Canary leaks: " + (json.dumps({k: v.get('leaked') for k, v in canary.items()}) if canary else "not run"),
         f"- Roster: " + ("ok" if not roster_problems else "; ".join(roster_problems)),
         "", f"**Hypothesis the run supports:** {hyp}.", ""]
    if mock:
        L.append("This was a mock run. It exercises the pipeline and produces every artifact, and none of its content is evidence about TSR.")
    return "\n".join(L)
